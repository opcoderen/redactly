/* ============================================================
 * 隐码 Redactly - 敏感信息识别规则库
 * ------------------------------------------------------------
 * 本文件只放"规则数据"，检测逻辑（OCR 行分析、bbox 映射、
 * 标签邻近匹配）在 assets/app.js 里，两边通过 window.DAMA_RULES 解耦。
 *
 * ▎如何加一条检测器
 *   往 DETECTORS 数组加一项：
 *   { type: "唯一id", label: "列表里显示的名字", re: /正则/g, validate: (m) => bool }
 *   - re 必须带 g 标志；建议用 (?<!\d) / (?!\d) 防止匹配长数字的一段
 *   - validate 可选：返回 false 则丢弃该命中（做二次校验防误报）
 *   - 检测顺序 = 数组顺序，先到的优先用于标签邻近去重
 *
 * ▎如何加一个"标签"（号 : 值 场景）
 *   LABELS_RE：往竖线列表里加词即可（长的放前面），如"检疫号"
 *   —— 命中后会自动打它右侧/下方的值，无需写值的正则
 *
 * ▎如何加一个"姓名类标签"
 *   NAME_LABELS_RE：加词后，标签后的中文名/拼音大写会被自动打
 * ============================================================ */

(function (global) {
  "use strict";

  /* ---------- 校验函数 ---------- */

  const luhn = (num) => {
    let sum = 0, alt = false;
    for (let i = num.length - 1; i >= 0; i--) {
      let d = +num[i];
      if (alt) { d *= 2; if (d > 9) d -= 9; }
      sum += d; alt = !alt;
    }
    return sum % 10 === 0;
  };

  /* ---------- 正则检测器 ---------- */

  const DETECTORS = [
    { type: "phone",    label: "手机号",   re: /(?<!\d)1[3-9]\d{9}(?!\d)/g },
    { type: "idcard",   label: "身份证",   re: /(?<!\d)[1-9]\d{5}(?:19|20)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\d{3}[\dXx](?!\d)/g },
    { type: "email",    label: "邮箱",     re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g },
    { type: "uscc",     label: "信用代码", re: /(?<![0-9A-Z])[0-9A-HJ-NPQRTUWXY]{2}\d{6}[0-9A-HJ-NPQRTUWXY]{10}(?![0-9A-Z])/g, validate: (m) => !/^\d+$/.test(m) },
    { type: "bankcard", label: "银行卡",   re: /(?<!\d)\d{15,19}(?!\d)/g, validate: (m) => !/^1[3-9]\d{9}$/.test(m) && luhn(m) },
    { type: "invoice",  label: "发票号",   re: /(?<!\d)(?:\d{20}|\d{8})(?!\d)/g, validate: (m) => m.length !== 8 || !/^(?:19|20)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])$/.test(m) },
    { type: "ticket",   label: "客票号",   re: /(?<!\d)\d{3}-\d{10}(?!\d)/g },
    { type: "landline", label: "座机",     re: /(?<!\d)0\d{2,3}[-\s]?\d{7,8}(?!\d)/g },
    { type: "amount",   label: "金额",     re: /[¥￥$€£]\s?\d[\d,]*(?:\.\d{1,2})?|\d[\d,]*(?:\.\d{2})\s?元/g },
    { type: "url",      label: "网址",     re: /https?:\/\/[^\s，。,]{4,}/g },
    { type: "date",     label: "日期",     re: /(?:19|20)\d{2}[./年\-]\s?\d{1,2}[./月\-]\s?\d{1,2}日?/g },
    { type: "mrz",      label: "机读码",   re: /(?<![A-Z0-9<])[A-Z0-9<]{28,44}(?![A-Z0-9<])/g },
    { type: "plate",    label: "车牌",     re: /[京津沪渝冀豫云辽黑湘皖鲁新苏浙赣鄂桂甘晋蒙陕吉闽贵粤青藏川宁琼使领][A-HJ-NP-Z][A-HJ-NP-Z0-9]{4,6}[A-HJ-NP-Z0-9挂学警港澳]/g },
  ];

  /* ---------- 标签库：「标签 + 值」邻近检测 ----------
     命中标签后自动打其右侧同行或下一行的值（格式不限）。 */

  const LABELS_RE = /(快递单号|运单号|客票号|常旅客号|门诊号|急诊号|病历号|病例号|病案号|就诊号|住院号|登记号|流水号|票据号|发票号|单据号|受理号|检验号|检查号|条码号|标本号|会员卡号|会员号|订单号|取件码|单号|编号|卡号|账号|户号|工号|学号|案号|床号|票号|证号|联系电话|联系人电话|电话|手机|号码)(?:号码|号|码)?(?![0-9A-Za-z])/g;

  /* ---------- 姓名标签库：「姓名 + 名字」邻近检测 ----------
     标签后的中文名（2-4 字，支持·）或拼音大写会被自动打。 */

  const NAME_LABELS_RE = /(姓名|收款人|付款人|户名|被保险人|投保人|经办人|领款人|申请人)(?![0-9A-Za-z])/g;
  const CJK_NAME_RE = /^[\u4e00-\u9fa5]{2,4}(?:[·•][\u4e00-\u9fa5]{2,4})?/;
  const PINYIN_NAME_RE = /^[A-Z]{2,12}(?:[·•\s][A-Z]{2,12}){0,3}/;

  global.DAMA_RULES = { DETECTORS, LABELS_RE, NAME_LABELS_RE, CJK_NAME_RE, PINYIN_NAME_RE, luhn };
})(window);
